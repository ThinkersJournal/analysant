/// Split one identifier into words: snake_case on `_`, CamelCase on
/// lower->Upper boundaries, SCREAMING_SNAKE on `_`. All lowercase.
/// `pick_route` -> [pick, route]; `RuleRegistry` -> [rule, registry];
/// `LOOKAHEAD_K` -> [lookahead, k].
pub fn split_ident_words(name: &str) -> Vec<String> {
    let mut words = Vec::new();
    let mut cur = String::new();
    let mut prev_lower_or_digit = false;
    for ch in name.chars() {
        if ch == '_' {
            if !cur.is_empty() {
                words.push(std::mem::take(&mut cur));
            }
            prev_lower_or_digit = false;
        } else if ch.is_uppercase() {
            if prev_lower_or_digit && !cur.is_empty() {
                words.push(std::mem::take(&mut cur));
            }
            cur.push(ch.to_ascii_lowercase());
            prev_lower_or_digit = false;
        } else {
            cur.push(ch);
            prev_lower_or_digit = ch.is_lowercase() || ch.is_ascii_digit();
        }
    }
    if !cur.is_empty() {
        words.push(cur);
    }
    words
}

/// A path is test-only when it lives under `tests/` or `benches/`, or
/// in a crate whose name says it is test code: anything containing
/// `fixture` (`fuel-model-fixture`, `fuel-correctness-fixtures`) or
/// `test-support` (`fuel-test-support`, whose own lib.rs calls it
/// "Shared test-gate helpers"). The brief named only `-fixture`; the
/// tree has the plural and the support crate too, same kind, so the
/// rule covers them and the report says so.
pub fn is_test_only_path(rel_path: &str) -> bool {
    let segments: Vec<&str> = rel_path.split('/').collect();
    if segments
        .iter()
        .any(|s| *s == "tests" || *s == "tests.rs" || *s == "benches" || *s == "benches.rs")
    {
        return true;
    }
    match segments.first() {
        Some(first) => first.contains("fixture") || first.contains("test-support"),
        None => false,
    }
}

fn is_ident_start(ch: char) -> bool {
    ch.is_ascii_alphabetic() || ch == '_'
}

fn is_ident_char(ch: char) -> bool {
    ch.is_ascii_alphanumeric() || ch == '_'
}

/// One cleaned line: comments stripped, string and char literal
/// contents masked (so a `//` or `{` inside a string cannot corrupt
/// the scan), with the comment text kept for the comment-word set.
struct CleanLine {
    text: String,
    comment_only: bool,
    comment_text: String,
    test_ctx: bool,
}

/// Strip comments and mask literals, tracking block-comment state
/// across lines. Returns the cleaned lines; `file_test` marks every
/// line test context (a `#![cfg(test)]` file).
fn clean_lines(text: &str, file_test: bool) -> Vec<CleanLine> {
    let mut out = Vec::new();
    let mut in_block = 0u32; // Rust block comments nest.
    for raw in text.lines() {
        let mut cleaned = String::with_capacity(raw.len());
        let mut comment = String::new();
        let chars: Vec<char> = raw.chars().collect();
        let mut i = 0;
        let mut in_str = false;
        let mut in_char = false;
        let mut in_raw_str: Option<usize> = None; // number of `#`s
        let mut escaped = false;
        while i < chars.len() {
            let ch = chars[i];
            if in_block > 0 {
                if ch == '/' && i + 1 < chars.len() && chars[i + 1] == '*' {
                    in_block += 1;
                    comment.push_str("/*");
                    i += 2;
                } else if ch == '*' && i + 1 < chars.len() && chars[i + 1] == '/' {
                    in_block -= 1;
                    comment.push_str("*/");
                    i += 2;
                } else {
                    comment.push(ch);
                    i += 1;
                }
                continue;
            }
            if in_str {
                if escaped {
                    escaped = false;
                } else if ch == '\\' {
                    escaped = true;
                } else if ch == '"' {
                    in_str = false;
                    cleaned.push('"');
                }
                i += 1;
                continue;
            }
            if in_char {
                if escaped {
                    escaped = false;
                } else if ch == '\\' {
                    escaped = true;
                } else if ch == '\'' {
                    in_char = false;
                }
                i += 1;
                continue;
            }
            if let Some(hashes) = in_raw_str {
                if ch == '"' {
                    // Raw string ends at `"` followed by the same `#`s.
                    let mut ok = true;
                    for h in 0..hashes {
                        if chars.get(i + 1 + h) != Some(&'#') {
                            ok = false;
                            break;
                        }
                    }
                    if ok {
                        in_raw_str = None;
                        cleaned.push('"');
                        i += 1 + hashes;
                        continue;
                    }
                }
                i += 1;
                continue;
            }
            // Normal state.
            if ch == '/' && i + 1 < chars.len() && chars[i + 1] == '/' {
                comment.extend(chars[i..].iter());
                break;
            }
            if ch == '/' && i + 1 < chars.len() && chars[i + 1] == '*' {
                in_block = 1;
                comment.push_str("/*");
                i += 2;
                continue;
            }
            if ch == '"' {
                in_str = true;
                cleaned.push('"');
                i += 1;
                continue;
            }
            if ch == 'r' {
                // Raw string: r"..." or r#"..."#.
                let mut j = i + 1;
                let mut hashes = 0;
                while chars.get(j) == Some(&'#') {
                    hashes += 1;
                    j += 1;
                }
                if chars.get(j) == Some(&'"') {
                    in_raw_str = Some(hashes);
                    cleaned.push('"');
                    i = j + 1;
                    continue;
                }
            }
            if ch == '\'' {
                // A char literal is `'x'` or `'\e'`; a lifetime `'a`
                // is not. Only treat it as a literal when the shape
                // matches, so lifetimes never mask code.
                let next = chars.get(i + 1);
                let next2 = chars.get(i + 2);
                let next3 = chars.get(i + 3);
                let is_char = match (next, next2, next3) {
                    (Some(&c), Some(&'\''), _) if c != '\\' && c != '\'' => true,
                    (Some(&'\\'), Some(_), Some(&'\'')) => true,
                    (Some(&'\\'), Some(_), Some(_)) => {
                        // `\u{...}` escapes: scan to the closing quote.
                        let mut k = i + 2;
                        let mut closed = false;
                        while k < chars.len() && k < i + 10 {
                            if chars[k] == '\'' {
                                closed = true;
                                break;
                            }
                            k += 1;
                        }
                        closed
                    }
                    _ => false,
                };
                if is_char {
                    in_char = true;
                    i += 1;
                    continue;
                }
            }
            cleaned.push(ch);
            i += 1;
        }
        let comment_only = cleaned.trim().is_empty();
        out.push(CleanLine {
            text: cleaned,
            comment_only,
            comment_text: comment,
            test_ctx: file_test,
        });
    }
    out
}

#[derive(Debug, Clone)]
enum ScopeKind {
    Mod { test: bool },
    Impl { ty: String },
    Enum { name: String },
    Struct { name: String },
    Trait { name: String },
    Fn { test: bool },
    Other,
}

#[derive(Debug, Clone)]
struct Scope {
    kind: ScopeKind,
    test: bool,
    open_depth: i32,
}

fn scope_test(s: &Scope) -> bool {
    s.test
}

/// Parse the name after a keyword: the first identifier starting at
/// `from` (skipping whitespace). Returns the name and the byte index
/// just past it.
fn parse_ident_after(s: &str, from: usize) -> Option<(String, usize)> {
    let bytes = s.as_bytes();
    let mut i = from;
    while i < bytes.len() && (bytes[i] as char).is_whitespace() {
        i += 1;
    }
    let start = i;
    if i >= bytes.len() || !is_ident_start(bytes[i] as char) {
        return None;
    }
    while i < bytes.len() && is_ident_char(bytes[i] as char) {
        i += 1;
    }
    Some((s[start..i].to_string(), i))
}

/// Strip a `pub`, `pub(...)`, or `pub(crate)` prefix; returns the rest.
fn strip_pub(s: &str) -> Option<&str> {
    let t = s.trim_start();
    let mut rest = t.strip_prefix("pub")?;
    if let Some(after_paren) = rest.strip_prefix('(') {
        let idx = after_paren.find(')')?;
        rest = &after_paren[idx + 1..];
    }
    if rest.is_empty() || rest.starts_with(|c: char| c.is_whitespace()) {
        Some(rest)
    } else {
        None
    }
}

/// The `impl` line's implementing type and (for trait impls) trait:
/// `impl Foo` -> (Foo, None); `impl Rule for FusionRule` ->
/// (FusionRule, Some(Rule)); generics and lifetimes are skipped.
fn parse_impl(s: &str) -> Option<(String, Option<String>)> {
    let t = s.trim_start();
    let rest = t.strip_prefix("impl")?;
    if rest.is_empty() || !(rest.starts_with(|c: char| c.is_whitespace() || c == '<')) {
        return None;
    }
    // Skip generic params `<...>` and lifetimes.
    let mut i = 0;
    let bytes = rest.as_bytes();
    while i < bytes.len() && (bytes[i] as char).is_whitespace() {
        i += 1;
    }
    if i < bytes.len() && bytes[i] == b'<' {
        let mut depth = 0;
        while i < bytes.len() {
            match bytes[i] {
                b'<' => depth += 1,
                b'>' => {
                    depth -= 1;
                    if depth == 0 {
                        i += 1;
                        break;
                    }
                }
                _ => {}
            }
            i += 1;
        }
    }
    let (first, after) = parse_ident_after(rest, i)?;
    let mut j = after;
    while j < bytes.len() && (bytes[j] as char).is_whitespace() {
        j += 1;
    }
    if rest[j..].starts_with("for ") || rest[j..].starts_with("for\t") {
        let (ty, _) = parse_ident_after(rest, j + 3)?;
        Some((ty, Some(first)))
    } else {
        Some((first, None))
    }
}

fn push_item(defs: &mut Vec<CodeItem>, def_lines: &mut HashSet<(usize, String)>, item: CodeItem) {
    def_lines.insert((item.line, item.name.clone()));
    defs.push(item);
}

