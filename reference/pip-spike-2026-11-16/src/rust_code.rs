//! Slice 6: the Rust language pack — code as ground truth.
//!
//! The design (Eric's, from the requirements note): "languages" means
//! as distant as English versus Rust, so claims in text documents can
//! be transparently checked against the code. The language-pack seam is
//! a Rust tokenizer: signatures, tests, and types as the code's claims.
//!
//! This module is a hand-rolled line-pattern scanner, std-only, no
//! `syn`, no external crates (Cargo.toml has zero dependencies). That
//! is a deliberate spike constraint, and it bounds what the scanner
//! can see — the gaps are named at the end of this module's docs and
//! in the report:
//!
//! - No parser: items are recognized by line shapes (`pub fn name(`,
//!   `pub struct Name`, `impl Trait for Type`, ...). A definition
//!   split across lines, or written in an unusual shape, is missed.
//! - No call graph: a "use" is a textual mention (a call `name(`, a
//!   field read `.name`, any occurrence for a type). The scanner cannot
//!   tell whether a production caller is itself reachable from the
//!   realize path — dead production code reads as BUILT. That is the
//!   `pick_route` case: called from `RouteCache::resolve`, which is
//!   itself never called.
//! - No macro expansion: items generated by macros do not exist for
//!   this scanner (their invocations do — as mentions of the macro
//!   name, not of the generated items).
//! - No `cfg` evaluation beyond literal `#[cfg(test)]`: feature-gated
//!   code (e.g. `#[cfg(any(feature = "cuda", test))]`) reads as
//!   production. A `#[cfg(test)]` written any other way
//!   (`#[cfg(all(test, ...))]`) is not recognized.
//! - No string-aware brace counting beyond masking `"..."`, `'x'`,
//!   and `r#"..."#` literals; a brace inside an unmasked literal
//!   miscounts scope depth. Raw strings with more than one `#` are
//!   handled; format-string braces are masked with the string.
//! - Items are keyed by bare name: every `new`, every `resolve`, every
//!   `len` in the tree is one item. A method name is conflated across
//!   impls; the qualified name (`Type::method`) is kept on the item for
//!   the exact-match path, but use-counting is by bare name.
//!
//! Statuses (the lens's own words — weaker than the audit's, stated
//! here so the validation table can be read honestly):
//! - BUILT: a production definition exists AND at least one production
//!   use. "Production use" is textual, not reachability.
//! - STUB: a production definition exists, zero production uses. The
//!   audit's STUB ("a type exists, nothing constructs or reads it")
//!   is the same shape; the audit's "on the realize path" is stronger.
//! - TEST-ONLY: no production definition; definitions and/or uses only
//!   in test or fixture code.
//! - ABSENT: no definition and no code mention. "Comments only" is
//!   recorded separately: the words appear in comments, not code.

