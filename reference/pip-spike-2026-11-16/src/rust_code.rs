#[derive(Debug, Clone)]
pub struct CodeItem {
    pub name: String,
    /// Impl type for methods (`RouteCache` for `resolve`), enum name
    /// for variants (`Op` for `Branch`), trait for impls (`Model` for
    /// `LocalModel`). None for free items.
    pub qualified: Option<String>,
    pub kind: CodeItemKind,
    /// Path relative to the code root, e.g.
    /// `fuel-dispatch/src/ranker/route_picker.rs`.
    pub file: String,
    pub line: usize,
    pub test_only: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MentionKind {
    /// Followed by `(`: a call. The only thing that counts as a use
    /// of a function — a `use` import line is not a call.
    Call,
    /// Preceded by `.`: a field read. A struct-literal `name:` init
    /// is not a read.
    DotRead,
    /// Any other whole-word occurrence.
    Plain,
}

#[derive(Debug, Clone)]
pub struct Mention {
    pub file: String,
    pub line: usize,
    pub test_only: bool,
    pub kind: MentionKind,
}

#[derive(Default)]
pub struct CodeIndex {
    pub items: Vec<CodeItem>,
    /// Word -> every whole-word occurrence outside comments, with
    /// the definition lines and `pub use` lines removed.
    pub mentions: HashMap<String, Vec<Mention>>,
    /// Words seen inside comments (line, doc, and block), identifier-
    /// split, so "PlanStore" in a comment yields `plan` and `store`.
    pub comment_words: HashSet<String>,
    pub files_scanned: usize,
    pub rs_files: usize,
}

