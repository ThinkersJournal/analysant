impl CodeIndex {
    /// Scan one file's text as if it lived at `rel_path` (path
    /// relative to the code root, `/`-separated). Used by the tests;
    /// `scan_code_dir` is the real entry point.
    pub fn add_source(&mut self, rel_path: &str, text: &str) {
        self.files_scanned += 1;
        let file_test = is_test_only_path(rel_path)
            || text
                .lines()
                .any(|l| l.trim_start().starts_with("#![cfg(test)]"));
        let mut lines = clean_lines(text, file_test);
        // Comment words: every identifier word inside a comment,
        // identifier-split, so `PlanStore` yields plan + store.
        for line in &lines {
            for word in split_comment_words(&line.comment_text) {
                self.comment_words.insert(word);
            }
        }
        let mut def_lines: HashSet<(usize, String)> = HashSet::new();
        let mut defs: Vec<CodeItem> = Vec::new();
        let mut stack: Vec<Scope> = Vec::new();
        let mut depth: i32 = 0;
        let mut pending_cfg_test = false;
        let mut pending_test_attr = false;

        for (idx, line) in lines.iter_mut().enumerate() {
            let line_no = idx + 1;
            let text = line.text.clone();
            let trimmed = text.trim_start().to_string();
            let in_test = file_test || stack.iter().any(scope_test) || pending_test_attr;
            line.test_ctx = in_test;
            if text.contains("#[cfg(test)]") {
                pending_cfg_test = true;
            }
            if text.contains("#[test]") {
                pending_test_attr = true;
            }
            // (Recorded via push_item below; a closure would hold the
            // mutable borrows while the impl branch also touches them.)
            let mut decl_scope: Option<ScopeKind> = None;
            let mut consumed_pending = false;

            // `pub use ...` is a re-export, not a definition or a use.
            let is_pub_use = trimmed.starts_with("pub use ");
            if !is_pub_use {
                if let Some(rest) = strip_pub(&trimmed) {
                    let rest = rest.trim_start();
                    if let Some(after) = rest
                        .strip_prefix("fn ")
                        .or_else(|| rest.strip_prefix("async fn "))
                        .or_else(|| rest.strip_prefix("unsafe fn "))
                        .or_else(|| rest.strip_prefix("async unsafe fn "))
                        .or_else(|| rest.strip_prefix("const fn "))
                    {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            let qualified = current_impl_type(&stack);
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name: name.clone(),
                                    qualified,
                                    kind: CodeItemKind::Fn,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    // Methods inherit fixture-ness
                                    // from their impl type (see the
                                    // plain-fn branch below).
                                    test_only: in_test
                                        || name.ends_with("Fixture")
                                        || current_impl_is_fixture(&stack),
                                },
                            );
                            decl_scope = Some(ScopeKind::Fn { test: in_test });
                            consumed_pending = true;
                        }
                    } else if let Some(after) = rest.strip_prefix("struct ") {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name: name.clone(),
                                    qualified: None,
                                    kind: CodeItemKind::Struct,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test || name.ends_with("Fixture"),
                                },
                            );
                            decl_scope = Some(ScopeKind::Struct { name: name.clone() });
                            consumed_pending = true;
                        }
                    } else if let Some(after) = rest.strip_prefix("enum ") {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name: name.clone(),
                                    qualified: None,
                                    kind: CodeItemKind::Enum,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test || name.ends_with("Fixture"),
                                },
                            );
                            decl_scope = Some(ScopeKind::Enum { name: name.clone() });
                            consumed_pending = true;
                        }
                    } else if let Some(after) = rest.strip_prefix("trait ") {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name: name.clone(),
                                    qualified: None,
                                    kind: CodeItemKind::Trait,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test,
                                },
                            );
                            decl_scope = Some(ScopeKind::Trait { name });
                            consumed_pending = true;
                        }
                    } else if let Some(after) = rest.strip_prefix("type ") {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name,
                                    qualified: None,
                                    kind: CodeItemKind::Type,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test,
                                },
                            );
                            consumed_pending = true;
                        }
                    } else if let Some(after) = rest.strip_prefix("const ") {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name,
                                    qualified: None,
                                    kind: CodeItemKind::Const,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test,
                                },
                            );
                            consumed_pending = true;
                        }
                    } else if let Some(after) = rest.strip_prefix("static ") {
                        if let Some((name, _)) = parse_ident_after(after, 0) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name,
                                    qualified: None,
                                    kind: CodeItemKind::Static,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test,
                                },
                            );
                            consumed_pending = true;
                        }
                    } else if in_struct_scope(&stack) {
                        // A `pub` field inside a struct: `pub coupling: ...`.
                        if let Some((name, after)) = parse_ident_after(rest, 0) {
                            let tail = rest[after..].trim_start();
                            if tail.starts_with(':') {
                                let qualified = current_struct_name(&stack);
                                push_item(
                                    &mut defs,
                                    &mut def_lines,
                                    CodeItem {
                                        name,
                                        qualified,
                                        kind: CodeItemKind::Field,
                                        file: rel_path.to_string(),
                                        line: line_no,
                                        test_only: in_test,
                                    },
                                );
                                consumed_pending = true;
                            }
                        }
                    }
                } else if trimmed.starts_with("impl")
                    && trimmed[4..].starts_with(|c: char| c.is_whitespace() || c == '<')
                {
                    if let Some((ty, tr)) = parse_impl(&trimmed) {
                        def_lines.insert((line_no, ty.clone()));
                        if let Some(tr) = &tr {
                            def_lines.insert((line_no, tr.clone()));
                        }
                        defs.push(CodeItem {
                            name: ty.clone(),
                            qualified: tr,
                            kind: CodeItemKind::Impl,
                            file: rel_path.to_string(),
                            line: line_no,
                            test_only: in_test || ty.ends_with("Fixture"),
                        });
                        decl_scope = Some(ScopeKind::Impl { ty });
                        consumed_pending = true;
                    }
                } else if trimmed.starts_with("mod ") {
                    let is_test_mod = pending_cfg_test;
                    decl_scope = Some(ScopeKind::Mod { test: is_test_mod });
                    consumed_pending = true;
                } else if let Some(fn_pos) = fn_prefix_len(&trimmed) {
                    // A plain fn counts as a method (inside an impl
                    // or trait block) or a test fn; top-level private
                    // fns are out of scope for this scanner.
                    let method_of =
                        current_impl_type(&stack).or_else(|| current_trait_name(&stack));
                    if let Some(ty) = method_of {
                        if let Some((name, _)) = parse_ident_after(&trimmed, fn_pos) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name: name.clone(),
                                    qualified: Some(ty),
                                    kind: CodeItemKind::Fn,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    // Methods inherit fixture-ness from
                                    // their impl type: `impl Model for
                                    // FixtureModel { fn name }` is
                                    // scaffolding even in a plain file.
                                    test_only: in_test
                                        || name.ends_with("Fixture")
                                        || current_impl_is_fixture(&stack),
                                },
                            );
                            decl_scope = Some(ScopeKind::Fn { test: in_test });
                            consumed_pending = true;
                        }
                    } else if pending_test_attr {
                        if let Some((name, _)) = parse_ident_after(&trimmed, 3) {
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name,
                                    qualified: None,
                                    kind: CodeItemKind::Fn,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: true,
                                },
                            );
                            decl_scope = Some(ScopeKind::Fn { test: true });
                            consumed_pending = true;
                        }
                    }
                } else if in_enum_scope(&stack) {
                    if let Some((name, _)) = parse_ident_after(&trimmed, 0) {
                        if name
                            .chars()
                            .next()
                            .map(|c| c.is_uppercase())
                            .unwrap_or(false)
                        {
                            let qualified = current_enum_name(&stack);
                            push_item(
                                &mut defs,
                                &mut def_lines,
                                CodeItem {
                                    name,
                                    qualified,
                                    kind: CodeItemKind::Variant,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test,
                                },
                            );
                            consumed_pending = true;
                        }
                    }
                }
            }
            if consumed_pending {
                pending_cfg_test = false;
                pending_test_attr = false;
            }

            // Variants / fields on the enum's or struct's opening line:
            // `pub enum Op { Branch { x: u8 }, Scan }` puts them after
            // the first `{` on the same line.
            if let Some(ScopeKind::Enum { name }) = &decl_scope {
                let name = name.clone();
                if let Some(rest) = text.split_once('{').map(|(_, r)| r) {
                    for seg in rest.split(',') {
                        if let Some((v, _)) = parse_ident_after(seg.trim_start(), 0) {
                            if v.chars().next().map(|c| c.is_uppercase()).unwrap_or(false) {
                                def_lines.insert((line_no, v.clone()));
                                defs.push(CodeItem {
                                    name: v,
                                    qualified: Some(name.clone()),
                                    kind: CodeItemKind::Variant,
                                    file: rel_path.to_string(),
                                    line: line_no,
                                    test_only: in_test,
                                });
                            }
                        }
                    }
                }
            }

            // Brace tracking, left to right: `{` pushes the pending
            // declaration scope (or Other), `}` pops scopes whose
            // opening depth is now above the current depth.
            let mut first_open = decl_scope.is_some();
            for ch in text.chars() {
                match ch {
                    '{' => {
                        depth += 1;
                        if first_open {
                            first_open = false;
                            let kind = decl_scope.take().unwrap();
                            let test = match &kind {
                                ScopeKind::Mod { test } => *test,
                                ScopeKind::Fn { test } => *test,
                                _ => in_test,
                            };
                            stack.push(Scope {
                                kind,
                                test,
                                open_depth: depth,
                            });
                        } else {
                            stack.push(Scope {
                                kind: ScopeKind::Other,
                                test: in_test,
                                open_depth: depth,
                            });
                        }
                    }
                    '}' => {
                        depth -= 1;
                        while let Some(top) = stack.last() {
                            if top.open_depth > depth {
                                stack.pop();
                            } else {
                                break;
                            }
                        }
                    }
                    _ => {}
                }
            }
            if decl_scope.is_some() {
                // The declaration had no `{` on this line (e.g.
                // `mod foo;`): nothing to push. Clear it so it cannot
                // attach to a later line's brace.
                let _ = decl_scope.take();
            }
        }

        // Mentions: every identifier word on a code line, except
        // definition lines for that word and `pub use` re-export lines.
        for (idx, line) in lines.iter().enumerate() {
            let line_no = idx + 1;
            if line.comment_only {
                continue;
            }
            let trimmed = line.text.trim_start();
            if trimmed.starts_with("pub use ") {
                continue;
            }
            let bytes = line.text.as_bytes();
            let mut i = 0;
            while i < bytes.len() {
                let ch = bytes[i] as char;
                if is_ident_start(ch) {
                    let start = i;
                    while i < bytes.len() && is_ident_char(bytes[i] as char) {
                        i += 1;
                    }
                    let word = &line.text[start..i];
                    if def_lines.contains(&(line_no, word.to_string())) {
                        continue;
                    }
                    let prev = if start > 0 {
                        Some(bytes[start - 1] as char)
                    } else {
                        None
                    };
                    let next = bytes.get(i).map(|b| *b as char);
                    let kind = if next == Some('(') {
                        MentionKind::Call
                    } else if prev == Some('.') {
                        MentionKind::DotRead
                    } else {
                        MentionKind::Plain
                    };
                    self.mentions
                        .entry(word.to_string())
                        .or_default()
                        .push(Mention {
                            file: rel_path.to_string(),
                            line: line_no,
                            test_only: line.test_ctx,
                            kind,
                        });
                } else {
                    i += 1;
                }
            }
        }
        self.items.extend(defs);
    }

    /// All definitions of one bare name, in scan order.
    pub fn definitions_of(&self, name: &str) -> Vec<&CodeItem> {
        self.items.iter().filter(|i| i.name == name).collect()
    }

    /// Production and test uses of one bare name, by item kind:
    /// functions count calls (`name(`), fields count reads (`.name`),
    /// everything else counts any occurrence. Definition lines,
    /// `pub use` lines, and comments never count.
    pub fn uses_of(&self, name: &str, kind: CodeItemKind) -> (usize, usize) {
        let mut prod = 0;
        let mut test = 0;
        if let Some(mentions) = self.mentions.get(name) {
            for m in mentions {
                let counts = match kind {
                    CodeItemKind::Fn => m.kind == MentionKind::Call,
                    CodeItemKind::Field => m.kind == MentionKind::DotRead,
                    _ => true,
                };
                if counts {
                    if m.test_only {
                        test += 1;
                    } else {
                        prod += 1;
                    }
                }
            }
        }
        (prod, test)
    }

    /// The doc-vs-code verdict for one doc claim. Matching, in order:
    /// (1) for Identifier claims, the exact last segment of the
    ///     identifier's path (`Op::Branch` -> `Branch`, preferring the
    ///     item qualified by the path prefix, `Op`); (2) the word rule:
    ///     the doc key's content tokens are all family-matched by the
    ///     code name's words, or the code name has >= 2 words all
    ///     family-matched by the doc key. A one-word code name can never
    ///     satisfy a multi-word doc key — that is what keeps the `Judge`
    ///     type from "building" the bundled Judge baseline.
    pub fn doc_code_status(&self, claim: &Claim, aliases: &[AliasGroup]) -> DocCodeVerdict {
        let canonical = canonicalize(&claim.key, aliases);
        let key = content_words(&canonical);
        if key.is_empty() {
            return DocCodeVerdict {
                status: CodeStatus::Absent,
                matched: None,
                comments_only: false,
            };
        }
        // (1) Exact identifier match.
        if claim.kind == ClaimKind::Identifier {
            let text = claim.text.trim();
            let segments: Vec<&str> = text.split("::").flat_map(|s| s.split('.')).collect();
            if let Some(last) = segments.last() {
                let last = last.trim().trim_end_matches(|c: char| !is_ident_char(c));
                if !last.is_empty() && last.chars().next().map(is_ident_start).unwrap_or(false) {
                    let prefix = if segments.len() > 1 {
                        Some(segments[..segments.len() - 1].join("::"))
                    } else {
                        None
                    };
                    let mut candidates: Vec<&CodeItem> = self
                        .items
                        .iter()
                        .filter(|i| i.name == last && i.kind != CodeItemKind::Impl)
                        .collect();
                    candidates.sort_by(|a, b| {
                        let qa = a.qualified.as_deref() == prefix.as_deref();
                        let qb = b.qualified.as_deref() == prefix.as_deref();
                        qb.cmp(&qa)
                            .then_with(|| a.file.cmp(&b.file))
                            .then_with(|| a.line.cmp(&b.line))
                    });
                    if let Some(item) = candidates.first() {
                        return self.status_for(item);
                    }
                }
            }
        }
        // (2) The word rule.
        let mut best: Option<(&CodeItem, usize)> = None;
        for item in self.items.iter().filter(|i| i.kind != CodeItemKind::Impl) {
            for words in item_word_sets(item) {
                if matches_words(&key, &words) {
                    let rank = words.len();
                    let better = match &best {
                        None => true,
                        Some((prev, prev_rank)) => {
                            rank < *prev_rank
                                || (rank == *prev_rank
                                    && (item.file.as_str(), item.line)
                                        < (prev.file.as_str(), prev.line))
                        }
                    };
                    if better {
                        best = Some((item, rank));
                    }
                    break;
                }
            }
        }
        match best {
            Some((item, _)) => self.status_for(item),
            None => DocCodeVerdict {
                status: CodeStatus::Absent,
                matched: None,
                comments_only: key.iter().all(|t| self.comment_words.contains(*t)),
            },
        }
    }

    fn status_for(&self, item: &CodeItem) -> DocCodeVerdict {
        let matched = MatchedItem {
            name: item.name.clone(),
            qualified: item.qualified.clone(),
            kind: item.kind,
            file: item.file.clone(),
            line: item.line,
        };
        let defs = self.definitions_of(&item.name);
        let has_prod_def = defs.iter().any(|d| !d.test_only);
        let has_test_def = defs.iter().any(|d| d.test_only);
        let (prod_uses, test_uses) = self.uses_of(&item.name, item.kind);
        let status = if has_prod_def && prod_uses > 0 {
            CodeStatus::Built
        } else if has_prod_def {
            CodeStatus::Stub
        } else if has_test_def || test_uses > 0 {
            CodeStatus::TestOnly
        } else {
            CodeStatus::Absent
        };
        DocCodeVerdict {
            status,
            matched: Some(matched),
            comments_only: false,
        }
    }
}

/// The word sets an item can match with: its bare name's words, and
/// (for qualified items) the qualifier's words plus the name's words
/// (`RouteCache::resolve` -> [route, cache, resolve]).
fn item_word_sets(item: &CodeItem) -> Vec<Vec<String>> {
    let mut sets = vec![split_ident_words(&item.name)];
    if let Some(q) = &item.qualified {
        let mut words = split_ident_words(q);
        words.extend(split_ident_words(&item.name));
        sets.push(words);
    }
    sets
}

/// True when the doc key's content tokens are all family-matched by
/// the code name's words, or the code name has >= 2 words all
/// family-matched by the doc key. `same_family` (slice 5) is the
/// morphology: identical, trailing `s`, or a 6+ letter shared prefix.
fn matches_words(key: &[&str], words: &[String]) -> bool {
    if key.is_empty() || words.is_empty() {
        return false;
    }
    let key_covered = key.iter().all(|k| words.iter().any(|w| same_family(k, w)));
    if key_covered {
        return true;
    }
    if words.len() >= 2 {
        return words.iter().all(|w| key.iter().any(|k| same_family(k, w)));
    }
    false
}

fn split_comment_words(comment: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    for ch in comment.chars() {
        if is_ident_char(ch) {
            cur.push(ch);
        } else if !cur.is_empty() {
            out.extend(split_ident_words(&cur));
            cur.clear();
        }
    }
    if !cur.is_empty() {
        out.extend(split_ident_words(&cur));
    }
    out
}

fn current_impl_type(stack: &[Scope]) -> Option<String> {
    stack.iter().rev().find_map(|s| match &s.kind {
        ScopeKind::Impl { ty } => Some(ty.clone()),
        _ => None,
    })
}

fn current_impl_is_fixture(stack: &[Scope]) -> bool {
    stack.iter().rev().any(|s| match &s.kind {
        ScopeKind::Impl { ty } => ty.ends_with("Fixture"),
        _ => false,
    })
}

fn current_trait_name(stack: &[Scope]) -> Option<String> {
    stack.iter().rev().find_map(|s| match &s.kind {
        ScopeKind::Trait { name } => Some(name.clone()),
        _ => None,
    })
}

/// If `s` starts with a fn-declaration prefix (`fn `, `async fn `,
/// `unsafe fn `, `async unsafe fn `, `const fn `), return the offset
/// just past `fn `.
fn fn_prefix_len(s: &str) -> Option<usize> {
    for p in [
        "async unsafe fn ",
        "async fn ",
        "unsafe fn ",
        "const fn ",
        "fn ",
    ] {
        if let Some(rest) = s.strip_prefix(p) {
            return Some(s.len() - rest.len());
        }
    }
    None
}

fn current_enum_name(stack: &[Scope]) -> Option<String> {
    stack.iter().rev().find_map(|s| match &s.kind {
        ScopeKind::Enum { name } => Some(name.clone()),
        _ => None,
    })
}

fn current_struct_name(stack: &[Scope]) -> Option<String> {
    stack.iter().rev().find_map(|s| match &s.kind {
        ScopeKind::Struct { name } => Some(name.clone()),
        _ => None,
    })
}

fn in_enum_scope(stack: &[Scope]) -> bool {
    matches!(stack.last().map(|s| &s.kind), Some(ScopeKind::Enum { .. }))
}

fn in_struct_scope(stack: &[Scope]) -> bool {
    matches!(
        stack.last().map(|s| &s.kind),
        Some(ScopeKind::Struct { .. })
    )
}

/// Recursively scan every `.rs` file under `root` (sorted, for a
/// deterministic run). Paths in the index are relative to `root`.
pub fn scan_code_dir(root: &Path) -> CodeIndex {
    let mut index = CodeIndex::default();
    let mut files = Vec::new();
    collect_rs_files(root, &mut files);
    files.sort();
    for path in files {
        let rel = path
            .strip_prefix(root)
            .unwrap_or(&path)
            .to_string_lossy()
            .replace('\\', "/");
        match std::fs::read_to_string(&path) {
            Ok(text) => {
                index.rs_files += 1;
                index.add_source(&rel, &text);
            }
            Err(_) => {
                // A non-UTF-8 .rs file is skipped, not fatal: the
                // scanner reads text, and a binary file is not code
                // it can tokenize. (No such file exists in this tree.)
            }
        }
    }
    index
}

fn collect_rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    let mut entries: Vec<_> = entries.filter_map(|e| e.ok()).collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let path = entry.path();
        let ft = match entry.file_type() {
            Ok(t) => t,
            Err(_) => continue,
        };
        if ft.is_dir() {
            collect_rs_files(&path, out);
        } else if ft.is_file() && path.extension().map(|x| x == "rs").unwrap_or(false) {
            out.push(path);
        }
    }
}
